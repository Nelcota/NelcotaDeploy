#!/usr/bin/env bash
# Measure the numbers quoted in docs/status.md and rewrite only the block
# between <!-- generated:numbers:start --> and <!-- generated:numbers:end -->.
#
# Usage: scripts/report-numbers.sh [--playwright-json FILE | --skip-playwright]
#   --playwright-json FILE  reuse a Playwright JSON report instead of running the suite
#   --skip-playwright       leave the Playwright row as "not measured"
# Without either Playwright option the script runs the browser suite against
# bin/nelcota-panel (make build) with the host's Node and Playwright, like make e2e.
set -euo pipefail
fail() { printf 'Error: %s\n' "$1" >&2; exit 1; }
root=$(cd "$(dirname "$0")/.." && pwd)
report=$root/docs/status.md
start='<!-- generated:numbers:start -->'
end='<!-- generated:numbers:end -->'
playwright_json='' skip_playwright=false
while (($#)); do
	case $1 in
	--playwright-json) playwright_json=$(realpath "${2:?--playwright-json needs a file}"); shift 2 ;;
	--skip-playwright) skip_playwright=true; shift ;;
	*) fail "Unknown argument: $1" ;;
	esac
done
command -v jq >/dev/null 2>&1 || fail 'jq is required'
if ! grep -qxF "$start" "$report" || ! grep -qxF "$end" "$report"; then
	fail "Markers $start / $end are missing in docs/status.md"
fi
work=$(mktemp -d)
trap 'rm -rf -- "$work"' EXIT
cd "$root"

# Asset budgets: both tests log the measured Brotli sizes with -v.
if ! go test -count=1 -v -run 'TestAssetBudget|TestPageScriptBudget' ./web/... > "$work/budget.txt" 2>&1; then
	cat "$work/budget.txt" >&2
	fail 'Budget tests failed; numbers were not updated'
fi
totals=$(sed -n 's/.*total JavaScript \([0-9]*\) B, CSS \([0-9]*\) B (Brotli).*/\1 \2/p' "$work/budget.txt")
[[ $totals =~ ^[0-9]+\ [0-9]+$ ]] || fail 'TestAssetBudget did not log the JavaScript and CSS totals'
read -r js css <<< "$totals"
sed -n 's/.*budget_test\.go:[0-9]*: \(\/[^ ]*\) *\([0-9]*\) B$/\1 \2/p' "$work/budget.txt" | LC_ALL=C sort > "$work/pages.txt"
[[ -s $work/pages.txt ]] || fail 'TestPageScriptBudget did not log per-page sizes'
kb() { awk -v b="$1" 'BEGIN { printf "%.1f KB", b / 1000 }'; }
page() { awk -v p="$1" '$1 == p { print $2 }' "$work/pages.txt"; }
servers=$(page /servers) logs=$(page /apps/dev-app-api/logs)
[[ -n $servers && -n $logs ]] || fail 'Per-page sizes for /servers and the logs page are missing'
others=$(awk '$1 != "/servers" && $1 != "/apps/dev-app-api/logs" { if ($2 > max) max = $2; n++ } END { print max + 0, n + 0 }' "$work/pages.txt")
read -r other_max other_count <<< "$others"

# Browser suite: counts come from Playwright's JSON reporter.
playwright_row='not measured (run scripts/report-numbers.sh without --skip-playwright)'
if [[ $skip_playwright == false ]]; then
	if [[ -z $playwright_json ]]; then
		[[ -x bin/nelcota-panel ]] || fail 'bin/nelcota-panel is missing; run make build first'
		[[ -d web/node_modules/@playwright/test ]] || fail 'Install Playwright first: cd web && npm ci && npx playwright install chromium'
		playwright_json=$work/playwright.json
		(cd web && PLAYWRIGHT_JSON_OUTPUT_NAME="$playwright_json" npx playwright test --reporter=json) > "$work/playwright.log" 2>&1 || true
		[[ -s $playwright_json ]] || { cat "$work/playwright.log" >&2; fail 'Playwright produced no JSON report'; }
	fi
	read -r expected unexpected flaky skipped < <(jq -er '.stats | "\(.expected) \(.unexpected) \(.flaky) \(.skipped)"' "$playwright_json") ||
		fail 'Unreadable Playwright JSON report'
	if ((unexpected != 0 || flaky != 0)); then
		jq -r '.. | objects | select(has("specs")) | .specs[] | select(.ok == false) | "  failed: \(.file):\(.line) \(.title)"' "$playwright_json" >&2 || true
		fail "Playwright reported $unexpected failed and $flaky flaky tests; numbers were not updated"
	fi
	browser=$(cd web && node -p 'require("@playwright/test/package.json").version' 2>/dev/null || printf unknown)
	playwright_row="$expected pass, $skipped skipped (opt-in suites), 0 failed — Chromium, @playwright/test $browser"
fi

commit=$(git rev-parse --short=12 HEAD)
[[ -z $(git status --porcelain --untracked-files=no) ]] || commit="$commit with uncommitted changes"
# shellcheck disable=SC2016 # Backticks are Markdown code spans, not expansions.
{
	printf '%s\n' "$start"
	printf '%s\n' '| Measure | Value |' '| --- | --- |'
	printf '| Playwright browser tests | %s |\n' "$playwright_row"
	printf '| All JavaScript (Brotli) | %s (`TestAssetBudget`, budget < 100 KB) |\n' "$(kb "$js")"
	printf '| All CSS (Brotli) | %s (`TestAssetBudget`, budget < 50 KB) |\n' "$(kb "$css")"
	printf '| Page JavaScript, Logs | %s (`TestPageScriptBudget`) |\n' "$(kb "$logs")"
	printf '| Page JavaScript, Servers | %s (`TestPageScriptBudget`) |\n' "$(kb "$servers")"
	printf '| Page JavaScript, largest of %s other pages | %s (`TestPageScriptBudget`) |\n' "$other_count" "$(kb "$other_max")"
	printf '\n_Generated by `make report-numbers` at commit `%s` with %s. Do not edit by hand._\n' "$commit" "$(go env GOVERSION)"
	printf '%s\n' "$end"
} > "$work/block.md"

awk -v start="$start" -v end="$end" -v block="$work/block.md" '
$0 == start { while ((getline line < block) > 0) print line; skip = 1; next }
$0 == end { skip = 0; next }
!skip { print }' "$report" > "$work/report.md"
cat "$work/report.md" > "$report"
printf 'Updated the measured numbers in docs/status.md:\n'
cat "$work/block.md"
