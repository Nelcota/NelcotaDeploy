// TestEnglishOnly enforces the English-only rule from AGENTS.md: repository
// content and filenames must not contain Portuguese outside the interface
// translation catalog. It walks the files Git tracks plus untracked files that
// are not ignored, so it also catches violations before they are committed.
//
// The detector is deliberately conservative. A line is flagged when it
// contains a letter that Portuguese uses and English does not (see
// portugueseLetters), or a whole word from portugueseWords. Words are matched
// after splitting on every non-letter, so identifiers such as
// CHAVE_PUBLICA or homologacao-v1 are caught, while English words that merely
// contain the same letters are not.
func TestEnglishOnly(t *testing.T) {
	root := repoRoot(t)
	files := trackedFiles(t, root)
	if len(files) == 0 {
		t.Fatal("git ls-files returned no files; run the test inside the repository checkout")
	}
	var violations []string
	used := map[int]bool{}
	for _, name := range files {
		violations = append(violations, checkName(name)...)
		if skipContent(name) {
			continue
		}
		data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(name)))
		if err != nil {
			if os.IsNotExist(err) {
				continue // Deleted in the working tree but still in the index.
			}
			t.Fatal(err)
		}
		if isBinary(data) {
			continue
		}
		violations = append(violations, checkContent(name, data, used)...)
	}
	for i, entry := range allowed {
		if !used[i] {
			violations = append(violations, fmt.Sprintf("%s: stale allowlist entry %q; remove it from internal/policy/english_test.go", entry.path, entry.text))
		}
	}
	if len(violations) > 0 {
		t.Fatalf("Portuguese text found outside %s (AGENTS.md requires English; add a commented allowlist entry only for proper names or immutable identifiers):\n%s",
			catalog, strings.Join(violations, "\n"))
	}
}

// catalog is the only file allowed to contain Portuguese.
const catalog = "web/i18n/pt_br.go"

// portugueseLetters are accented letters Portuguese uses that English text
// and this project's identifiers do not.
const portugueseLetters = "ãõçâêôáéíóúàÃÕÇÂÊÔÁÉÍÓÚÀ"

// portugueseWords are common Portuguese words that are not English words.
// Entries are lowercase and without accents; tokens are folded the same way
// before comparison, so "não" and "nao" both match "nao".
var portugueseWords = map[string]bool{
	"nao": true, "voce": true, "voces": true, "tambem": true, "entao": true,
	"obrigado": true, "obrigada": true, "porque": true, "quando": true,
	"onde": true, "isso": true, "isto": true, "aqui": true, "agora": true,
	"ainda": true, "depois": true, "muito": true, "fazer": true, "deve": true,
	"pode": true, "senha": true, "usuario": true, "usuarios": true,
	"servidor": true, "servidores": true, "arquivo": true, "arquivos": true,
	"erro": true, "falha": true, "sucesso": true, "chave": true,
	"publica": true, "conferida": true, "configuracao": true,
	"configuracoes": true, "aplicacao": true, "aplicativo": true,
	"implantacao": true, "atualizacao": true, "seguranca": true,
	"homologacao": true, "validacao": true, "evidencias": true, "loja": true,
}

// skippedPrefixes are vendored, generated, or binary-only trees.
var skippedPrefixes = []string{
	"internal/gen/",         // Generated from Protobuf.
	"internal/store/dbgen/", // Generated by sqlc.
	"web/static/vendor/",    // Vendored third-party libraries.
	"web/static/dist/",      // Fingerprinted build output.
	"web/ui/icons/",         // Vendored icon set.
	"docs/screenshots/",     // Generated images.
}

// skippedNames are files whose content is not authored project text.
var skippedNames = []string{
	catalog,
	"go.sum",
	"web/package-lock.json",
	// This test necessarily lists the Portuguese words it rejects.
	"internal/policy/english_test.go",
}

// skippedExtensions are binary or machine-generated formats.
var skippedExtensions = []string{
	".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico", ".avif",
	".woff", ".woff2", ".ttf", ".otf", ".eot",
	".br", ".zst", ".gz", ".zip", ".tar", ".tgz", ".pgo", ".pdf",
	".lock",
}

// allowed lists proper names and immutable identifiers that contain
// Portuguese. Each entry permits one exact substring in one file; the line is
// checked again with the substring removed, so other Portuguese on the same
// line is still reported. Keep every entry commented with its reason.
var allowed = []struct{ path, text string }{
	// Historical local staging artifacts and the laboratory signing-key path.
	// These are file names inside signed archives and the original signed
	// delivery report; AGENTS.md requires preserving them exactly.
	{"docs/staging-releases.md", "dist/evidencias-homologacao.tar.gz"},
	{"docs/staging-releases.md", "dist/VALIDACAO.md"},
	{"docs/staging-releases.md", "dist/homologacao.minisign.pub"},
	{"docs/staging-releases.md", "nelcota-release-homologacao"},
}

func repoRoot(t *testing.T) string {
	t.Helper()
	out, err := exec.Command("git", "rev-parse", "--show-toplevel").Output()
	if err != nil {
		t.Fatalf("git is required for the English-only check: %v", err)
	}
	return strings.TrimSpace(string(out))
}

func trackedFiles(t *testing.T, root string) []string {
	t.Helper()
	cmd := exec.Command("git", "ls-files", "-z", "--cached", "--others", "--exclude-standard")
	cmd.Dir = root
	out, err := cmd.Output()
	if err != nil {
		t.Fatalf("git ls-files failed: %v", err)
	}
	var files []string
	for name := range strings.SplitSeq(string(out), "\x00") {
		if name != "" {
			files = append(files, name)
		}
	}
	slices.Sort(files)
	return slices.Compact(files)
}

func skipContent(name string) bool {
	if slices.Contains(skippedNames, name) {
		return true
	}
	for _, prefix := range skippedPrefixes {
		if strings.HasPrefix(name, prefix) {
			return true
		}
	}
	if strings.HasSuffix(name, "_templ.go") {
		return true // Generated by templ from the checked .templ source.
	}
	return slices.Contains(skippedExtensions, strings.ToLower(filepath.Ext(name)))
}

func isBinary(data []byte) bool {
	head := data[:min(len(data), 8192)]
	return bytes.IndexByte(head, 0) >= 0 || !utf8.Valid(head) ||
		bytes.Contains(head, []byte("Code generated")) && bytes.Contains(head, []byte("DO NOT EDIT"))
}

// checkName flags Portuguese in any path component. The catalog's own name is
// English, so no file is exempt from this check.
func checkName(name string) []string {
	if reason := portuguese(name); reason != "" {
		return []string{fmt.Sprintf("%s: filename %s", name, reason)}
	}
	return nil
}

func checkContent(name string, data []byte, used map[int]bool) []string {
	var violations []string
	scanner := bufio.NewScanner(bytes.NewReader(data))
	scanner.Buffer(make([]byte, 0, 64*1024), 16*1024*1024)
	for line := 1; scanner.Scan(); line++ {
		text := scanner.Text()
		for i, entry := range allowed {
			if entry.path == name && strings.Contains(text, entry.text) {
				text = strings.ReplaceAll(text, entry.text, "")
				used[i] = true
			}
		}
		if reason := portuguese(text); reason != "" {
			violations = append(violations, fmt.Sprintf("%s:%d: %s: %s", name, line, reason, excerpt(scanner.Text())))
		}
	}
	return violations
}

// portuguese returns a short reason when text looks Portuguese, or "".
func portuguese(text string) string {
	if i := strings.IndexAny(text, portugueseLetters); i >= 0 {
		r, _ := utf8.DecodeRuneInString(text[i:])
		return fmt.Sprintf("letter %q", r)
	}
	for _, word := range strings.FieldsFunc(text, func(r rune) bool { return !unicode.IsLetter(r) }) {
		if portugueseWords[fold(word)] {
			return fmt.Sprintf("word %q", word)
		}
	}
	return ""
}

// accentFolder maps the accented letters Portuguese uses to plain ASCII.
var accentFolder = strings.NewReplacer(
	"ã", "a", "á", "a", "â", "a", "à", "a", "õ", "o", "ó", "o", "ô", "o",
	"é", "e", "ê", "e", "í", "i", "ú", "u", "ü", "u", "ç", "c",
)

// fold lowercases a word and removes Portuguese accents.
func fold(word string) string {
	return accentFolder.Replace(strings.ToLower(word))
}

func excerpt(line string) string {
	line = strings.TrimSpace(line)
	if utf8.RuneCountInString(line) > 120 {
		line = string([]rune(line)[:117]) + "..."
	}
	return line
}

func TestPortugueseDetector(t *testing.T) {
	for _, row := range []struct {
		text string
		want bool
	}{
		{"Deploy the app to the server.", false},
		{"Não foi possível conectar", true},
		{"SIGNING_KEY='CHAVE_PUBLICA_MINISIGN_CONFERIDA'", true},
		{"scripts/homologacao/run.sh", true},
		{"configuração", true},
		{"Configure the pasta and the antes", false},
		{"servers := listServers()", false},
		{"Portuguese (Brazil)", false},
	} {
		if got := portuguese(row.text) != ""; got != row.want {
			t.Errorf("portuguese(%q) = %v, want %v", row.text, got, row.want)
		}
	}
}
